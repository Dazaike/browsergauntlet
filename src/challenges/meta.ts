export const CHALLENGES: ChallengeMeta[] = rows.map(([slug, title, level, objective, success, failure, hint, par], i) => ({
  id: `c${pad2(i + 1)}`,
  num: i + 1,
  slug,
  title,
  level,
  objective,
  success,
  failure,
  hint,
  par,
}))

export const CHALLENGE_BY_ID: Record<string, ChallengeMeta> = Object.fromEntries(CHALLENGES.map((c) => [c.id, c]))
export const CHALLENGE_BY_SLUG: Record<string, ChallengeMeta> = Object.fromEntries(CHALLENGES.map((c) => [c.slug, c]))

export function findChallenge(slugOrId: string | undefined): ChallengeMeta | undefined {
  if (!slugOrId) return undefined
  return CHALLENGE_BY_SLUG[slugOrId] ?? CHALLENGE_BY_ID[slugOrId]
}

export function levelOf(c: ChallengeMeta): LevelMeta {
  return LEVELS[c.level - 1]
}
